import assert from 'node:assert/strict';
import Database from 'better-sqlite3';
import { mkdtempSync, statSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { NextRequest } from 'next/server';
import { migrate } from '../src/lib/db/migrations';

async function main() {
  let checks = 0;
  const check = (value: unknown, label: string) => { assert.ok(value, label); checks++; console.log('PASS ' + label); };
  const migrationDb = new Database(':memory:');
  const migrations = [{version:1,name:'first',up:()=>migrationDb.exec('CREATE TABLE sample(id INTEGER)')}];
  migrate(migrationDb,migrations); migrate(migrationDb,migrations);
  check((migrationDb.prepare('SELECT COUNT(*) n FROM schema_migrations').get() as any).n===1,'migration applies once');
  assert.throws(()=>migrate(migrationDb,[...migrations,{version:2,name:'failure',up:()=>{migrationDb.exec('CREATE TABLE rolled_back(id INTEGER)');throw Error('injected');}}]));
  check(!migrationDb.prepare("SELECT name FROM sqlite_master WHERE name='rolled_back'").get(),'failed migration rolls back DDL');
  assert.throws(()=>migrate(migrationDb,[]),/incompatible/);
  assert.throws(()=>migrate(migrationDb,[{...migrations[0],name:'changed'}]),/incompatible/);
  check(true,'downgrade and changed migration identity rejected');
  process.env.DATA_DIR=mkdtempSync(path.join(tmpdir(),'readiness-tests-'));
  process.env.APP_MODE='demo';process.env.APP_ORIGIN='http://localhost:3000';
  const {authDb}=await import('../src/lib/auth/store');
  const {tokenHash}=await import('../src/lib/auth/session');
  const {withMerchantScope}=await import('../src/lib/auth/context');
  const {getDb}=await import('../src/lib/db');
  const health=await import('../src/app/api/health/route');
  const checkout=await import('../src/app/api/storefront/checkout/route');
  const disputes=await import('../src/app/api/disputes/route');
  const carrier=await import('../src/app/api/carrier/update/route');
  const {realtimeHub}=await import('../src/lib/realtime/hub');
  const {getVaultEvidenceForDispute}=await import('../src/lib/vault/vault');
  const owner='usr_'+'a'.repeat(32),token='a'.repeat(64),now=new Date().toISOString();
  authDb().prepare('INSERT INTO accounts VALUES(?,?,?,?,?,?,?,?)').run(owner,'test@example.test','Test','Store','MERCHANT_ADMIN',null,'unused',now);
  authDb().prepare('INSERT INTO sessions VALUES(?,?,?,?)').run(tokenHash(token),owner,Date.now()+600000,Date.now());
  const scoped=<T>(fn:()=>T)=>withMerchantScope(owner,fn);
  const db=scoped(()=>getDb());
  check(health.GET().status===200,'health endpoint checks database without authentication');
  process.env.APP_MODE='invalid';check(health.GET().status===503,'invalid mode fails readiness');process.env.APP_MODE='demo';
  const source=path.join(process.env.DATA_DIR!,'backup-source.db'),destination=path.join(process.env.DATA_DIR!,'backup.db');
  const original=new Database(source);original.pragma('journal_mode = WAL');original.exec("CREATE TABLE retained(value TEXT); INSERT INTO retained VALUES('committed')");
  const backup=()=>spawnSync(process.execPath,['node_modules/tsx/dist/cli.mjs','scripts/backup-database.ts',source,destination],{encoding:'utf8'});
  check(backup().status===0,'online backup succeeds with source open in WAL mode');
  const restored=new Database(destination,{readonly:true});
  check((restored.prepare('SELECT value FROM retained').get() as any).value==='committed' && (statSync(destination).mode & 0o777)===0o600,'backup retains committed data with restricted permissions');
  restored.close();check(backup().status!==0,'backup refuses overwrite');original.close();
  // A pre-ledger environment-classified DB is adopted without dropping its records.
  const {initSchema}=await import('../src/lib/db/baseline');
  const legacy=new Database(':memory:');initSchema(legacy,'demo');
  legacy.prepare('INSERT INTO users(id,name,email,store_name,created_at) VALUES(?,?,?,?,?)').run('retained','Test','retained@test.example','Store',now);
  migrate(legacy,[{version:1,name:'environment-classified-baseline',up:()=>initSchema(legacy,'demo')}]);
  check(Boolean(legacy.prepare("SELECT id FROM users WHERE id='retained'").get()),'baseline adoption preserves pre-ledger records');
  legacy.close();
  const req=(body:unknown)=>new NextRequest('http://localhost:3000/api/test',{method:'POST',headers:{origin:'http://localhost:3000','content-type':'application/json',cookie:'dispute_session='+token},body:JSON.stringify(body)});
  const post=(route:any,body:unknown)=>route.POST(req(body),{params:{}});
  const input={buyer_name:'Buyer',buyer_email:'buyer@example.test',shipping_address:'1 Test Street',items:[{sku:'DJI-M3P-CINE',quantity:1,unit_price_cents:1,name:'forged'}]};
  for (const change of [{buyer_name:42},{items:[{sku:'missing',quantity:1}]},{items:[{sku:'DJI-M3P-CINE',quantity:0.5}]},{items:[{sku:'DJI-M3P-CINE',quantity:8},{sku:'DJI-M3P-CINE',quantity:8}]},{currency:'EUR'},{carrier:'unknown'}]) {
    check((await post(checkout,{...input,...change})).status===400,'malformed checkout rejected: '+JSON.stringify(change));
  }
  const order=(await (await post(checkout,input)).json()).order;
  check(order.total_cents===219900 && order.items[0].name!=='forged','server catalog controls price and name');
  const count=(table:string)=>(db.prepare(`SELECT COUNT(*) n FROM ${table}`).get() as any).n;
  const notifications:any[]=[];
  realtimeHub.on('system_event:demo:'+owner,event=>notifications.push(event));
  const beforeOrders=count('demo_orders'),beforeEvidence=count('evidence_items');
  db.exec("CREATE TRIGGER reject_evidence BEFORE INSERT ON evidence_items BEGIN SELECT RAISE(ABORT,'injected'); END");
  check((await post(checkout,input)).status===500 && count('demo_orders')===beforeOrders && count('evidence_items')===beforeEvidence && notifications.length===0,'checkout failure rolls back without events');
  db.exec('DROP TRIGGER reject_evidence');
  for (const body of [{amount_cents:-1},{amount_cents:1.5},{hours_until_deadline:'bad'},{reason:'bad'}]) check((await post(disputes,body)).status===400,'malformed dispute rejected');
  const beforeDisputes=count('disputes'),beforeDrafts=count('ai_drafts');notifications.length=0;
  db.exec("CREATE TRIGGER reject_dispute_draft BEFORE INSERT ON ai_drafts BEGIN SELECT RAISE(ABORT,'injected'); END");
  check((await post(disputes,{order_id:order.id})).status===500 && count('disputes')===beforeDisputes && count('ai_drafts')===beforeDrafts && notifications.length===0,'dispute creation rolls back if draft persistence fails');
  check(!db.prepare('SELECT id FROM evidence_items WHERE order_id=? AND dispute_id IS NOT NULL').get(order.id),'rollback restores original order evidence links');
  db.exec('DROP TRIGGER reject_dispute_draft');
  check((await post(disputes,{paypal_dispute_id:'duplicate-provider'})).status===200,'explicit provider identity accepted in demo');
  check((await post(disputes,{paypal_dispute_id:'duplicate-provider'})).status===409,'duplicate provider dispute returns conflict');
  const open=async()=> (await (await post(disputes,{order_id:order.id})).json()).dispute;
  const first=await open(),second=await open(),closed=await open(),reserved=await open();
  db.prepare("UPDATE disputes SET status='CLOSED' WHERE id=?").run(closed.id);
  db.prepare(`INSERT INTO approval_operations(id,dispute_id,action_type,snapshot_digest,snapshot,approver,idempotency_key,state,created_at,updated_at) VALUES(?,?,'ACCEPT_CLAIM','digest','{}',?,'key','UNCERTAIN',?,?)`).run('op',reserved.id,owner,now,now);
  const draftCount=(id:string)=>(db.prepare('SELECT COUNT(*) n FROM ai_drafts WHERE dispute_id=?').get(id) as any).n;
  const counts=[first,second,closed,reserved].map(d=>draftCount(d.id));
  notifications.length=0;
  db.exec("CREATE TRIGGER reject_draft BEFORE INSERT ON ai_drafts BEGIN SELECT RAISE(ABORT,'injected'); END");
  const carrierEvidence=count('evidence_items');
  check((await post(carrier,{order_id:order.id,target_status:'DELIVERED'})).status===500,'failed draft blocks partial carrier update');
  check((db.prepare('SELECT delivery_status FROM demo_orders WHERE id=?').get(order.id) as any).delivery_status==='LABEL_CREATED' && count('evidence_items')===carrierEvidence && notifications.length===0,'carrier transaction fully rolls back');
  db.exec('DROP TRIGGER reject_draft');
  check((await post(carrier,{order_id:order.id,target_status:'DELIVERED'})).status===200,'forward demo transition accepted');
  check(draftCount(first.id)===counts[0]+1 && draftCount(second.id)===counts[1]+1,'all open disputes on order receive updated draft');
  check(draftCount(closed.id)===counts[2] && draftCount(reserved.id)===counts[3],'terminal and reserved disputes retain drafts');
  check(scoped(()=>getVaultEvidenceForDispute(second.id)).some(e=>e.evidence_type==='PROOF_OF_DELIVERY'),'order evidence visible to second dispute');
  const deliveredCount=count('evidence_items'),drafts=count('ai_drafts');notifications.length=0;
  check((await post(carrier,{order_id:order.id,target_status:'DELIVERED'})).status===200 && count('evidence_items')===deliveredCount && count('ai_drafts')===drafts && notifications.length===0,'repeated carrier update is idempotent');
  check((await post(carrier,{order_id:order.id,target_status:'IN_TRANSIT'})).status===409,'backward transition rejected');
  check((await post(carrier,{order_id:order.id,target_status:42})).status===400,'invalid carrier enum rejected');
  console.log(`${checks} backend readiness checks passed.`);
}
main().catch(error=>{console.error(error);process.exitCode=1;});
